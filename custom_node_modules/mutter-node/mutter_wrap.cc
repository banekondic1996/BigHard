// Global context
static MetaContext *global_context = nullptr;
static GMainLoop *main_loop = nullptr;
static std::map<uint64_t, MetaWindow*> window_cache;

// Helper to get MetaDisplay
static MetaDisplay* get_display() {
    if (!global_context) return nullptr;
    return meta_context_get_display(global_context);
}

static guint32 get_activation_timestamp() {
    MetaDisplay *display = get_display();
    if (!display) return 0;
    return meta_display_get_current_time_roundtrip(display);
}

// Window Management Functions
napi_value MaximizeWindow(napi_env env, napi_callback_info info) {
    size_t argc = 1;
    napi_value args[1];
    napi_get_cb_info(env, info, &argc, args, nullptr, nullptr);
    
    if (argc < 1) {
        napi_throw_error(env, nullptr, "Window ID required");
        return nullptr;
    }
    
    int64_t window_id;
    napi_get_value_int64(env, args[0], &window_id);
    
    MetaWindow *window = window_cache[(uint64_t)window_id];
    if (window) {
        meta_window_maximize(window, META_MAXIMIZE_HORIZONTAL | META_MAXIMIZE_VERTICAL);
    }
    
    return nullptr;
}


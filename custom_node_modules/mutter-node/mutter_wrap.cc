napi_value IsMaximized(napi_env env, napi_callback_info info) {
    size_t argc = 1;
    napi_value args[1];
    napi_get_cb_info(env, info, &argc, args, nullptr, nullptr);
    
    int64_t window_id;
    napi_get_value_int64(env, args[0], &window_id);
    
    MetaWindow *window = window_cache[(uint64_t)window_id];
    napi_value result;
    
    if (window) {
        bool is_max = meta_window_is_maximized(window);
        napi_get_boolean(env, is_max, &result);
    } else {
        napi_get_boolean(env, false, &result);
    }
    
    return result;
}

napi_value GetCursorPosition(napi_env env, napi_callback_info info) {
    MetaDisplay *display = get_display();
    if (!display) {
        napi_throw_error(env, nullptr, "Mutter display not initialized");
        return nullptr;
    }
    
    MetaCursorTracker *tracker = meta_cursor_tracker_get_for_display(display);
    int x, y;
    meta_cursor_tracker_get_hot(tracker, &x, &y);
    
    napi_value result, x_val, y_val;
    napi_create_object(env, &result);
    napi_create_int32(env, x, &x_val);
    napi_create_int32(env, y, &y_val);
    napi_set_named_property(env, result, "x", x_val);
    napi_set_named_property(env, result, "y", y_val);
    
    return result;
}

napi_value GetWindows(napi_env env, napi_callback_info info) {
    MetaDisplay *display = get_display();
    if (!display) {
        napi_throw_error(env, nullptr, "Mutter display not initialized");
        return nullptr;
    }
    
    napi_value result;
    napi_create_array(env, &result);
    
    // Get all windows from display
    GList *windows = meta_display_list_all_windows(display);
    uint32_t index = 0;
    
    for (GList *l = windows; l != nullptr; l = l->next) {
        MetaWindow *window = META_WINDOW(l->data);
        uint64_t window_id = (uint64_t)window;
        window_cache[window_id] = window;
        
        napi_value window_obj;
        napi_create_object(env, &window_obj);
        
        napi_value id_val;
        napi_create_int64(env, window_id, &id_val);
        napi_set_named_property(env, window_obj, "id", id_val);
        
        // Get window title
        const char *title = meta_window_get_title(window);
        napi_value title_val;
        napi_create_string_utf8(env, title ? title : "", NAPI_AUTO_LENGTH, &title_val);
        napi_set_named_property(env, window_obj, "title", title_val);

        const char *gtk_app_id = meta_window_get_gtk_application_id(window);
        const char *wm_class = meta_window_get_wm_class(window);
        int32_t pid = meta_window_get_pid(window);
        bool minimized = meta_window_is_hidden(window);
        bool focused = meta_window_appears_focused(window);

        napi_value app_id_val;
        napi_create_string_utf8(env, gtk_app_id ? gtk_app_id : (wm_class ? wm_class : ""), NAPI_AUTO_LENGTH, &app_id_val);
        napi_set_named_property(env, window_obj, "app_id", app_id_val);

        napi_value class_val;
        napi_create_string_utf8(env, wm_class ? wm_class : "", NAPI_AUTO_LENGTH, &class_val);
        napi_set_named_property(env, window_obj, "wmClass", class_val);

        napi_value pid_val;
        napi_create_int32(env, pid, &pid_val);
        napi_set_named_property(env, window_obj, "pid", pid_val);

        napi_value minimized_val;
        napi_get_boolean(env, minimized, &minimized_val);
        napi_set_named_property(env, window_obj, "minimized", minimized_val);

        napi_value focused_val;
        napi_get_boolean(env, focused, &focused_val);
        napi_set_named_property(env, window_obj, "focused", focused_val);
        
        // Get window geometry
        MetaRectangle rect;
        meta_window_get_frame_rect(window, &rect);
        
        napi_value x_val, y_val, w_val, h_val;
        napi_create_int32(env, rect.x, &x_val);
        napi_create_int32(env, rect.y, &y_val);
        napi_create_int32(env, rect.width, &w_val);
        napi_create_int32(env, rect.height, &h_val);
        
        napi_set_named_property(env, window_obj, "x", x_val);
        napi_set_named_property(env, window_obj, "y", y_val);
        napi_set_named_property(env, window_obj, "width", w_val);
        napi_set_named_property(env, window_obj, "height", h_val);
        
        napi_set_element(env, result, index++, window_obj);
    }
    
    return result;
}

// Initialize Mutter
napi_value InitMutter(napi_env env, napi_callback_info info) {
    if (global_context) {
        napi_throw_error(env, nullptr, "Mutter already initialized");
        return nullptr;
    }
    
    // Create Mutter context
    GError *error = nullptr;
    global_context = meta_create_context("CustomShell");
    
    if (!meta_context_configure(global_context, nullptr, nullptr, &error)) {
        std::string err_msg = "Failed to configure Mutter: ";
        err_msg += error->message;
        g_error_free(error);
        napi_throw_error(env, nullptr, err_msg.c_str());
        return nullptr;
    }
    
    if (!meta_context_setup(global_context, &error)) {
        std::string err_msg = "Failed to setup Mutter: ";
        err_msg += error->message;
        g_error_free(error);
        napi_throw_error(env, nullptr, err_msg.c_str());
        return nullptr;
    }
    
    if (!meta_context_start(global_context, &error)) {
        std::string err_msg = "Failed to start Mutter: ";
        err_msg += error->message;
        g_error_free(error);
        napi_throw_error(env, nullptr, err_msg.c_str());
        return nullptr;
    }
    
    return nullptr;
}


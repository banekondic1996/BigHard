napi_value MoveWindow(napi_env env, napi_callback_info info) {
    size_t argc = 3;
    napi_value args[3];
    napi_get_cb_info(env, info, &argc, args, nullptr, nullptr);
    
    if (argc < 3) {
        napi_throw_error(env, nullptr, "Window ID, x, y required");
        return nullptr;
    }
    
    int64_t window_id;
    int32_t x, y;
    napi_get_value_int64(env, args[0], &window_id);
    napi_get_value_int32(env, args[1], &x);
    napi_get_value_int32(env, args[2], &y);
    
    MetaWindow *window = window_cache[(uint64_t)window_id];
    if (window) {
        meta_window_move_frame(window, TRUE, x, y);
    }
    
    return nullptr;
}

